/*
  Типограф: расставляет неразрывные пробелы, чтобы строка не кончалась
  предлогом, союзом или числом, а тире не начинало строку.
  Применяется ко всем текстам сайта при сборке — руками ничего ставить не нужно.
  Частицы «же», «ли», «бы» не привязываются: их можно переносить (решение Катерины).
*/

const NBSP = ' ';

// короткие слова, которые не остаются в конце строки: привязываются к следующему слову
const RU_SHORT = [
  'а', 'в', 'во', 'и', 'к', 'ко', 'о', 'об', 'обо', 'от', 'ото', 'с', 'со', 'у', 'я',
  'без', 'для', 'до', 'за', 'из', 'изо', 'на', 'над', 'не', 'ни', 'но', 'по',
  'под', 'при', 'про', 'да', 'или', 'то', 'как', 'что', 'его', 'её', 'их', 'мы', 'вы', 'он',
  'она', 'оно', 'они', 'это', 'все', 'всё', 'из-за', 'из-под',
];
const EN_SHORT = ['a', 'an', 'the', 'of', 'in', 'on', 'at', 'to', 'by', 'for', 'and', 'or', 'as', 'is', 'it', 'my', 'no', 'from', 'with'];

const SHORT = new RegExp(`(^|[\\s(«„"\\[—])((?:${[...RU_SHORT, ...EN_SHORT].join('|')}))\\s+`, 'giu');

export function typograph(input: string): string {
  if (!input) return input;
  let s = input.replace(/[ \t]+/g, ' ');

  // тире не начинает строку: пробел перед ним неразрывный
  s = s.replace(/ (—|–)(?= )/g, `${NBSP}$1`);

  // число держится со следующим словом или единицей: «4 апреля», «256 мм», «24 × 36»
  s = s.replace(/ × /g, `${NBSP}×${NBSP}`);
  s = s.replace(/(\d) (?=[\p{L}%½¼¾])/gu, `$1${NBSP}`);

  // инициалы и сокращения: «М. И. Туровская», «т. е.»
  s = s.replace(/(^|\s)(\p{Lu}\.) (?=\p{Lu})/gu, `$1$2${NBSP}`);

  // предлоги и союзы — несколько проходов, потому что они идут подряд («и в доме»)
  for (let i = 0; i < 3; i++) s = s.replace(SHORT, `$1$2${NBSP}`);

  return s;
}
